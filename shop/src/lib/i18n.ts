export const DICT: Record<Locale, Dict> = { fa, en };

/** کلید تودرتو با نقطه؛ اگر ترجمه نبود، فارسی برمی‌گردد و اگر نبود خود کلید */
export function t(locale: Locale, key: string, vars?: Record<string, string | number>): string {
  const read = (dict: Dict): string | undefined => {
    const value = key.split(".").reduce<unknown>((acc, part) => {
      if (acc && typeof acc === "object" && part in (acc as Dict)) return (acc as Dict)[part];
      return undefined;
    }, dict);
    return typeof value === "string" ? value : undefined;
  };

  let text = read(DICT[locale]) ?? read(DICT[DEFAULT_LOCALE]) ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

/** نسخهٔ آمادهٔ استفاده برای یک زبان: `const tr = translator(locale)` */
export function translator(locale: Locale) {
  return (key: string, vars?: Record<string, string | number>) => t(locale, key, vars);
}
